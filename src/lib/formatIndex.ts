/**
 * 0始まりの配列インデックスを、画面表示用の2桁ゼロ埋め文字列に変換する汎用関数。
 * カード・セクション見出し・目次で同じ採番表記を共有するために切り出してある。
 */

/**
 * 0始まりのindexを `01` `02` … の表示用ラベルにする。
 *
 * 1始まりに直してからゼロ埋めするため、`formatIndex(0)` は `"01"` を返す。
 * 100件以上になると3桁になるが、桁揃えの都合上あえて切り詰めていない。
 */
export function formatIndex(index: number): string {
  return String(index + 1).padStart(2, "0");
}
